#!/usr/bin/env node
/**
 * eval-scaffold.mjs  —  Gemini CLI Eval Developer Kit (Proof of Concept)
 * Usage: node scripts/eval-scaffold.mjs <behavior-tag> [--policy USUALLY_PASSES|ALWAYS_PASSES] [--output <path>]
 *
 * Example:
 *   node scripts/eval-scaffold.mjs tool_selection.destructive_action_confirm
 *   node scripts/eval-scaffold.mjs self_correction.tool_error_retry --policy ALWAYS_PASSES
 *
 * Reads from evals/behaviors.taxonomy.json and generates a ready-to-fill .eval.ts stub.
 *
 * GSoC 2026 EDK Proof of Concept — Himanshu Soni (@h30s)
 */
import { readFileSync, writeFileSync, existsSync } from 'fs';
import { resolve, join, dirname } from 'path';
import { parseArgs } from 'util';
import { fileURLToPath } from 'url';

// ─── Arg parsing ────────────────────────────────────────────────────────────
const { values, positionals } = parseArgs({
  args: process.argv.slice(2),
  options: {
    policy: { type: 'string', default: 'USUALLY_PASSES' },
    output: { type: 'string' },
    help:   { type: 'boolean', short: 'h', default: false },
  },
  allowPositionals: true,
});

if (values.help) {
  console.log(`
Usage: node scripts/eval-scaffold.mjs <behavior-tag> [options]

Arguments:
  behavior-tag     Dot-separated tag, e.g. tool_selection.destructive_action_confirm

Options:
  --policy         ALWAYS_PASSES | USUALLY_PASSES  (default: USUALLY_PASSES)
  --output <path>  Override output path (default: evals/<tag-as-kebab>.eval.ts)
  -h, --help       Show this help message
`);
  process.exit(0);
}

const behaviorTag = positionals[0];
if (!behaviorTag) {
  console.error(
    'Error: behavior-tag is required.\n' +
    'Usage: node scripts/eval-scaffold.mjs <behavior-tag> [--policy ALWAYS_PASSES|USUALLY_PASSES]',
  );
  process.exit(1);
}

const validPolicies = ['ALWAYS_PASSES', 'USUALLY_PASSES'];
if (!validPolicies.includes(values.policy)) {
  console.error(`❌ Invalid policy "${values.policy}". Must be one of: ${validPolicies.join(', ')}`);
  process.exit(1);
}

// ─── Load taxonomy ──────────────────────────────────────────────────────────
const __dirname = dirname(fileURLToPath(import.meta.url));
const repoRoot   = resolve(__dirname, '..');
const taxonomyPath = resolve(repoRoot, 'evals/behaviors.taxonomy.json');

let taxonomy;
try {
  taxonomy = JSON.parse(readFileSync(taxonomyPath, 'utf8'));
} catch (e) {
  console.error(`❌ Could not read taxonomy at: ${taxonomyPath}\n   ${e.message}`);
  process.exit(1);
}

// ─── Resolve behavior ───────────────────────────────────────────────────────
const parts = behaviorTag.split('.');
if (parts.length !== 2) {
  console.error(`❌ behavior-tag must be in the form "category.behavior_name". Got: "${behaviorTag}"`);
  process.exit(1);
}
const [categoryName, behaviorName] = parts;

const category = taxonomy.categories[categoryName];
if (!category) {
  const available = Object.keys(taxonomy.categories).join(', ');
  console.error(`❌ Unknown category "${categoryName}".\n   Available: ${available}`);
  process.exit(1);
}

const behavior = category.behaviors[behaviorName];
if (!behavior) {
  const available = Object.keys(category.behaviors).join(', ');
  console.error(`❌ Unknown behavior "${behaviorName}" in category "${categoryName}".\n   Available: ${available}`);
  process.exit(1);
}

// ─── Generate file ──────────────────────────────────────────────────────────
const fileName   = `${behaviorTag.replace(/\./g, '-')}.eval.ts`;
const outputPath = values.output ?? join(repoRoot, 'evals', fileName);

if (existsSync(outputPath)) {
  console.error(`❌ File already exists: ${outputPath}\n   Remove it first or use --output <path> to write elsewhere.`);
  process.exit(1);
}

const examplePrompts = behavior.example_prompts ?? [];
const firstPrompt    = examplePrompts[0] ?? 'TODO: Add a realistic prompt here';
const promptsComment = examplePrompts.slice(0, 2).map((p) => `//   - "${p}"`).join('\n');

const template = `/**
 * @license
 * Copyright 2025 Google LLC
 * SPDX-License-Identifier: Apache-2.0
 */

// AUTO-GENERATED by eval-scaffold.mjs (GSoC 2026 EDK Proof of Concept)
// evals/${fileName}
//
// behavior_tag: ${behaviorTag}
// criticality:  ${behavior.criticality}
// policy:       ${values.policy}
//
// Description:
//   ${behavior.description}
//
// Example prompts from taxonomy:
${promptsComment || '//   (none defined in taxonomy)'}
//
// TODO: Fill in realistic prompt(s) and assertions below.
// Run with: npx vitest run evals/${fileName}
// Docs: evals/README.md

import { evalTest } from './test-helper.js';

describe('${behaviorTag}', () => {
  evalTest('${values.policy}', {
    name: '${behavior.description.replace(/'/g, "\\'")}',
    prompt: '${firstPrompt.replace(/'/g, "\\'")}',
    assert: async (rig, result) => {
      // TODO: Add your assertions here.
      //
      // Useful patterns:
      //   const toolCalls = rig.getToolCalls('run_shell_command');
      //   expect(toolCalls).toHaveLength(0);
      //   expect(result).toMatch(/your expected output/i);
      //   expect(result.length).toBeGreaterThan(50);
      //
      throw new Error('Assertions not yet implemented — please fill in this eval.');
    },
  });
});
`;

writeFileSync(outputPath, template, 'utf8');

console.log(`✅ Scaffolded: ${outputPath}`);
console.log(`   behavior_tag: ${behaviorTag}`);
console.log(`   criticality:  ${behavior.criticality}`);
console.log(`   policy:       ${values.policy}`);
console.log(`\nNext steps:`);
console.log(`  1. Edit the prompt in ${outputPath}`);
console.log(`  2. Replace the TODO assertion with real checks`);
console.log(`  3. Run: npx vitest run evals/${fileName}`);
console.log(`  4. Submit a PR when the eval passes consistently`);
